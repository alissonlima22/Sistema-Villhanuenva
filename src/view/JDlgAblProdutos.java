    private void jBtnAblConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnAblConfirmarActionPerformed
        desabilitar(); 
        // TODO add your handling code here:
        AblProduto produto = new AblProduto();

    produto.setDescricao(jTxtAblDescricao.getText());
    produto.setTipo(jTxtAblTipo.getText());
    produto.setUnidade(jTxtAblUnidade.getText());
    produto.setPreco(Double.parseDouble(jFmtAblPreco.getText()));

    DaoProduto dao = new DaoProduto();

    if (!alterar) {

        if (dao.insert(produto)) {
            JOptionPane.showMessageDialog(this, "Produto cadastrado com sucesso!");
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao cadastrar produto!");
        }

    } else {

        produto.setId_produto(Integer.parseInt(jTxtAblCodigo.getText()));

        dao.update(produto);

        JOptionPane.showMessageDialog(this, "Produto alterado com sucesso!");
    }

    desabilitar();
    alterar = false;

    }//GEN-LAST:event_jBtnAblConfirmarActionPerformed

