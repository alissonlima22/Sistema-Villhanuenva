    private void jBtnAblAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnAblAlterarActionPerformed
        habilitar();        // TODO add your handling code here:
        alterar = true;
    habilitar();

    int id = Integer.parseInt(
            JOptionPane.showInputDialog(null, "Entre com o ID do produto"));

    DaoProduto dao = new DaoProduto();

    AblProduto produto = (AblProduto) dao.list(id);

    if (produto != null) {

        jTxtAblCodigo.setText(String.valueOf(produto.getId_produto()));
        jTxtAblDescricao.setText(produto.getDescricao());
        jTxtAblTipo.setText(produto.getTipo());
        jTxtAblUnidade.setText(produto.getUnidade());
        jFmtAblPreco.setText(String.valueOf(produto.getPreco()));

    } else {

        JOptionPane.showMessageDialog(this, "Produto não encontrado!");
        desabilitar();
        alterar = false;
    }
    }//GEN-LAST:event_jBtnAblAlterarActionPerformed

    private void jBtnAblExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnAblExcluirActionPerformed
        // TODO add your handling code here:
        int id = Integer.parseInt(
            JOptionPane.showInputDialog(null, "Entre com o ID do produto"));

    DaoProduto dao = new DaoProduto();
    AblProduto produto = (AblProduto) dao.list(id);

    if (produto != null) {

        int resp = JOptionPane.showConfirmDialog(
                null,
                "Deseja excluir o produto?",
                "Confirma",
                JOptionPane.YES_NO_OPTION);

        if (resp == JOptionPane.YES_OPTION) {
            dao.delete(produto);
            JOptionPane.showMessageDialog(this, "Produto excluído com sucesso!");
        }

    } else {

        JOptionPane.showMessageDialog(this, "Produto não encontrado!");
    }
    }//GEN-LAST:event_jBtnAblExcluirActionPerformed

